/** Нормализованные стеммы слов фразы без служебных слов. */
export function phraseToStems(phrase) {
    const norm = normalizeTextForIndex(String(phrase || ''));
    if (!norm) return [];
    const out = [];
    for (const w of norm.split(/[\s\-_]+/)) {
        if (!w || STOP.has(w)) continue;
        const st = stemWord(w);
        if (st && st.length >= 2) out.push(st);
    }
    return out;
}

let ready = false;
/** ключ фразы (стеммы через пробел) → Set индексов групп */
const phraseToGroups = new Map();
/** индекс группы → массив единиц (каждая — массив стеммов, ключ — строка) */
const groupUnits = [];
/** максимальная длина фразы в словах — для сегментации запроса */
let maxPhraseLen = 1;
/** ключ → Map(ключ → единица) из слабых групп */
const weakMap = new Map();

function ensure() {
    if (ready) return;
    ready = true;
    CONCEPT_GROUPS.forEach((group, gi) => {
        const seen = new Set();
        const units = [];
        for (const phrase of group) {
            const stems = phraseToStems(phrase);
            if (!stems.length) continue;
            const key = stems.join(' ');
            if (seen.has(key)) continue;
            seen.add(key);
            units.push({ key, stems });
            if (stems.length > maxPhraseLen) maxPhraseLen = stems.length;
            if (!phraseToGroups.has(key)) phraseToGroups.set(key, new Set());
            phraseToGroups.get(key).add(gi);
        }
        groupUnits[gi] = units;
    });
    for (const group of WEAK_GROUPS) {
        const units = group
            .map((p) => phraseToStems(p))
            .filter((st) => st.length)
            .map((stems) => ({ key: stems.join(' '), stems }));
        for (const a of units) {
            if (!weakMap.has(a.key)) weakMap.set(a.key, new Map());
            for (const b of units) if (b.key !== a.key) weakMap.get(a.key).set(b.key, b);
        }
    }
}

/** Самая длинная фраза тезауруса (в словах), не больше 4 — для скользящего окна по запросу. */
export function thesaurusMaxPhraseLen() {
    ensure();
    return Math.min(maxPhraseLen, 4);
}

/**
 * Единицы, близкие по смыслу к фразе (ключ = стеммы через пробел). Сама фраза не возвращается.
 * @param {string} key
 * @returns {Array<{key:string, stems:string[]}>}
 */
export function relatedUnitsForKey(key) {
    ensure();
    const groups = phraseToGroups.get(key);
    if (!groups) return [];
    const out = new Map();
    for (const gi of groups) {
        for (const u of groupUnits[gi]) if (u.key !== key && !out.has(u.key)) out.set(u.key, u);
    }
    return Array.from(out.values());
}

/** Есть ли фраза в тезаурусе. */
export function isThesaurusKey(key) {
    ensure();
    return phraseToGroups.has(key);
}

/**
 * Однословные стеммы, близкие по смыслу к стемму (совместимость со старым API smart-search).
 * @param {string} stem
 * @returns {Set<string>}
 */
export function relatedStems(stem) {
    const out = new Set();
    for (const u of relatedUnitsForKey(stem)) {
        if (u.stems.length === 1) out.add(u.stems[0]);
    }
    return out;
}

/**
 * Единицы той же темы (слабая связь). Ищутся и для самой фразы, и для её сильных синонимов
 * («подпись» → через «эцп» → сертификат, токен, КриптоПро…). Сильные синонимы не включаются.
 */
export function weakUnitsForKey(key) {
    ensure();
    const strongUnits = relatedUnitsForKey(key);
    const strong = new Set(strongUnits.map((u) => u.key));
    strong.add(key);
    const out = new Map();
    for (const k of [key, ...strongUnits.map((u) => u.key)]) {
        const m = weakMap.get(k);
        if (!m) continue;
        for (const u of m.values()) if (!strong.has(u.key) && !out.has(u.key)) out.set(u.key, u);
    }
    return Array.from(out.values());
}
