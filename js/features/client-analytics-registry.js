/** Регион по двум цифрам (ИНН или КПП). */
export function regionByCode(code2) {
    const c = String(code2 || '').slice(0, 2);
    if (!/^\d{2}$/.test(c)) return null;
    return RU_TAX_REGIONS[c] || RU_TAX_REGIONS[String(Number(c))] || null;
}

/**
 * Код причины постановки на учёт (5–6 знаки КПП). Диапазоны по общепринятому справочнику СППУНО:
 * 01–49 — российские организации, 50–99 — иностранные (но 50 у крупнейших налогоплательщиков).
 * @param {string} kpp
 * @returns {{ code: string, label: string } | null}
 */
export function kppReason(kpp) {
    const s = String(kpp || '');
    if (!/^\d{4}[\dA-Z]{2}\d{3}$/.test(s)) return null;
    const code = s.slice(4, 6);
    const n = Number(code);
    let label;
    if (code === '01') label = 'по месту нахождения организации';
    else if (code === '02' || code === '03') label = 'филиал (старый код, до 2008)';
    else if (code === '43') label = 'филиал';
    else if (code === '44') label = 'представительство';
    else if (code === '45') label = 'обособленное подразделение';
    else if (code === '50') label = 'крупнейший налогоплательщик';
    else if (n >= 4 && n <= 8) label = 'по месту нахождения имущества';
    else if (n >= 10 && n <= 29) label = 'по месту нахождения транспорта';
    else if (n >= 30 && n <= 42) label = 'иные основания (российская организация)';
    else if (n >= 46 && n <= 49) label = 'иные основания (российская организация)';
    else if (n >= 51 && n <= 99) label = 'иностранная организация';
    else label = 'код не распознан';
    return { code, label };
}

/**
 * Описание ИНН: тип субъекта, регион, инспекция, проверка контрольной суммы (передаётся снаружи).
 * @param {string} inn
 */
export function describeInn(inn) {
    const s = String(inn || '');
    if (!/^\d{10}$|^\d{12}$/.test(s)) return null;
    return {
        kind: s.length === 10 ? 'ЮЛ' : 'ФЛ/ИП',
        kindLong: s.length === 10 ? 'Юридическое лицо' : 'Физическое лицо / ИП',
        regionCode: s.slice(0, 2),
        region: regionByCode(s.slice(0, 2)),
        taxOffice: s.slice(0, 4),
    };
}

